import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(scriptDir, "..");
const outputPath = path.join(root, "docs", "reference", "nix-module.md");

const moduleRawUrl =
  "https://raw.githubusercontent.com/rodrgds/nix-config/refs/heads/main/modules/services/openpost/default.nix";
const moduleSourceUrl =
  "https://github.com/rodrgds/nix-config/blob/main/modules/services/openpost/default.nix";
const localModulePath = process.env.OPENPOST_NIX_MODULE_PATH;
const publicImage = "ghcr.io/getopenpost/openpost:latest";

function normalizeModuleForDocs(moduleSource) {
  return moduleSource.replace(
    /(^\s*default\s*=\s*")ghcr\.io\/(?:getopenpost|rodrgds)\/openpost(?:@sha256:[a-f0-9]{64}|:[^"]+)(";\s*$)/mu,
    `$1${publicImage}$2`,
  );
}

function renderMarkdown(moduleSource) {
  return [
    "<!-- Generated by scripts/sync-docs-external.mjs -->",
    "",
    `Source: [\`rodrgds/nix-config/modules/services/openpost/default.nix\`](${moduleSourceUrl})`,
    "",
    "The public example uses the moving `:latest` tag. The linked deployment source may pin a verified image digest.",
    "",
    "```nix",
    normalizeModuleForDocs(moduleSource).trimEnd(),
    "```",
    "",
  ].join("\n");
}

if (import.meta.main) {
  const flags = process.argv.slice(2);
  if (flags.some((flag) => flag !== "--refresh")) {
    throw new Error("Usage: bun scripts/sync-docs-external.mjs [--refresh]");
  }
  // Normal builds consume the reviewed snapshot without consulting moving upstream state.
  if (!localModulePath && !flags.includes("--refresh")) {
    await readFile(outputPath);
    console.log(`Using committed Nix module snapshot -> ${path.relative(root, outputPath)}`);
  } else {
    let moduleSource;
    if (localModulePath) {
      moduleSource = await readFile(localModulePath, "utf8");
    } else {
      const response = await fetch(moduleRawUrl, {
        headers: { "user-agent": "openpost-docs-build" },
      });
      if (!response.ok) throw new Error(`HTTP ${response.status} when fetching ${moduleRawUrl}`);
      moduleSource = await response.text();
    }
    await mkdir(path.dirname(outputPath), { recursive: true });
    await writeFile(outputPath, renderMarkdown(moduleSource), "utf8");
    console.log(`Synced Nix module -> ${path.relative(root, outputPath)}`);
  }
}
