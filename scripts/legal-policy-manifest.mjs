#!/usr/bin/env bun

import { execFileSync } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const manifestPath = path.join(root, "packages/legal-policy/src/manifest.json");
const generatedGoPath = path.join(
  root,
  "backend/internal/legalpolicy/manifest_generated.go",
);
const policyNames = ["terms", "privacy", "refunds"];
const documentKeys = [
  "effective_date",
  "requires_acceptance",
  "url",
  "version",
];
const isoDatePattern = /^\d{4}-\d{2}-\d{2}$/u;

function isIsoCalendarDate(value) {
  if (!isoDatePattern.test(value)) return false;
  const date = new Date(`${value}T00:00:00Z`);
  return (
    !Number.isNaN(date.getTime()) && date.toISOString().slice(0, 10) === value
  );
}

export async function readLegalPolicyManifest() {
  const manifest = JSON.parse(await readFile(manifestPath, "utf8"));
  validateLegalPolicyManifest(manifest);
  return manifest;
}

export function validateLegalPolicyManifest(manifest) {
  if (!manifest || typeof manifest !== "object" || Array.isArray(manifest)) {
    throw new Error("legal policy manifest must be an object");
  }
  const expectedKeys = ["privacy", "refunds", "schema_version", "terms"];
  assertExactKeys(manifest, expectedKeys, "legal policy manifest");
  if (manifest.schema_version !== 1) {
    throw new Error("legal policy manifest schema_version must be 1");
  }
  for (const name of policyNames) {
    const policy = manifest[name];
    assertExactKeys(policy, documentKeys, `${name} policy`);
    for (const field of ["version", "effective_date"]) {
      if (!isIsoCalendarDate(policy[field])) {
        throw new Error(`${name}.${field} must be an ISO calendar date`);
      }
    }
    if (policy.version !== policy.effective_date) {
      throw new Error(`${name} version must equal its effective date`);
    }
    const url = new URL(policy.url);
    if (
      url.protocol !== "https:" ||
      url.hostname !== "openpost.social" ||
      url.pathname !== `/${name}` ||
      url.search ||
      url.hash
    ) {
      throw new Error(`${name}.url must be https://openpost.social/${name}`);
    }
    if (typeof policy.requires_acceptance !== "boolean") {
      throw new Error(`${name}.requires_acceptance must be boolean`);
    }
  }
  if (!manifest.terms.requires_acceptance) {
    throw new Error("the official Terms require explicit acceptance");
  }
  if (!manifest.privacy.requires_acceptance) {
    throw new Error("the official Privacy Policy requires acknowledgement");
  }
  if (manifest.refunds.requires_acceptance) {
    throw new Error(
      "the Refund Policy is incorporated by the Terms, not accepted separately",
    );
  }
  return manifest;
}

function assertExactKeys(value, expected, label) {
  if (!value || typeof value !== "object" || Array.isArray(value)) {
    throw new Error(`${label} must be an object`);
  }
  const actual = Object.keys(value).sort();
  if (
    actual.length !== expected.length ||
    actual.some((key, index) => key !== expected[index])
  ) {
    throw new Error(`${label} must contain exactly ${expected.join(", ")}`);
  }
}

export function renderLegalPolicyGo(manifest) {
  validateLegalPolicyManifest(manifest);
  const source = `// Code generated by scripts/legal-policy-manifest.mjs; DO NOT EDIT.
package legalpolicy

const (
\tSchemaVersion = ${manifest.schema_version}

\tTermsVersion = ${JSON.stringify(manifest.terms.version)}
\tTermsEffectiveDate = ${JSON.stringify(manifest.terms.effective_date)}
\tTermsURL = ${JSON.stringify(manifest.terms.url)}

\tPrivacyVersion = ${JSON.stringify(manifest.privacy.version)}
\tPrivacyEffectiveDate = ${JSON.stringify(manifest.privacy.effective_date)}
\tPrivacyURL = ${JSON.stringify(manifest.privacy.url)}

\tRefundsVersion = ${JSON.stringify(manifest.refunds.version)}
\tRefundsEffectiveDate = ${JSON.stringify(manifest.refunds.effective_date)}
\tRefundsURL = ${JSON.stringify(manifest.refunds.url)}
\tRefundsRequiresAcceptance = ${manifest.refunds.requires_acceptance}
)
`;
  return execFileSync("gofmt", [], {
    input: source,
    encoding: "utf8",
    stdio: ["pipe", "pipe", "inherit"],
  });
}

export function renderLegalPolicyEnv(manifest) {
  validateLegalPolicyManifest(manifest);
  return (
    `OPENPOST_TERMS_URL=${manifest.terms.url}\n` +
    `OPENPOST_PRIVACY_URL=${manifest.privacy.url}\n` +
    `OPENPOST_TERMS_VERSION=${manifest.terms.version}\n` +
    `OPENPOST_PRIVACY_VERSION=${manifest.privacy.version}\n`
  );
}

async function main() {
  const command = process.argv[2] ?? "check";
  const manifest = await readLegalPolicyManifest();
  const generated = renderLegalPolicyGo(manifest);
  if (command === "generate") {
    await writeFile(generatedGoPath, generated);
    console.log(`Generated ${path.relative(root, generatedGoPath)}.`);
    return;
  }
  if (command === "check") {
    const current = await readFile(generatedGoPath, "utf8").catch(() => "");
    if (current !== generated) {
      throw new Error(
        "generated legal policy constants are stale; run bun scripts/legal-policy-manifest.mjs generate",
      );
    }
    console.log(
      "Validated canonical legal policy versions and generated constants.",
    );
    return;
  }
  if (command === "env") {
    process.stdout.write(renderLegalPolicyEnv(manifest));
    return;
  }
  throw new Error("usage: legal-policy-manifest.mjs [check|generate|env]");
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href
) {
  try {
    await main();
  } catch (error) {
    console.error(`legal-policy: ${error.message}`);
    process.exitCode = 1;
  }
}
