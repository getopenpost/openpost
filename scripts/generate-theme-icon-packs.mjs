import heroiconsCollection from "@iconify-json/heroicons/icons.json";
import lucideCollection from "@iconify-json/lucide/icons.json";
import phosphorCollection from "@iconify-json/ph/icons.json";
import tablerCollection from "@iconify-json/tabler/icons.json";
import { getIconData } from "@iconify/utils/lib/icon-set/get-icon";
import { iconToSVG } from "@iconify/utils/lib/svg/build";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { format } from "oxfmt";
import sharp from "sharp";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const packsDirectory = resolve(root, "apps/web/src/lib/themes/icons/packs");
const mobilePacksDirectory = resolve(root, "apps/mobile/src/theme/icon-packs");
const mobileAssetsDirectory = resolve(root, "apps/mobile/assets/theme-icons");
const packIDs = ["lucide", "heroicons-outline", "heroicons-solid", "phosphor", "tabler"];
const nativeTabRoles = ["drafts", "calendar", "queue"];
const nativeCollections = {
  lucide: lucideCollection,
  "heroicons-outline": heroiconsCollection,
  "heroicons-solid": heroiconsCollection,
  phosphor: phosphorCollection,
  tabler: tablerCollection,
};
const check = process.argv.includes("--check");

const { BUILTIN_ICON_ROLE_MAPS } = await import(
  resolve(root, "apps/mobile/src/theme/icon-packs.ts")
);

for (const id of packIDs) {
  const source = await import(`${packsDirectory}/${id}.ts`);
  const output = renderPack(source.default);
  const destination = resolve(packsDirectory, `${id}.generated.ts`);
  if (check) {
    const current = await readFile(destination, "utf8").catch(() => "");
    if (current !== output) {
      throw new Error(`${destination} is stale. Run bun scripts/generate-theme-icon-packs.mjs.`);
    }
    continue;
  }
  await writeFile(destination, output);
}

await mkdir(mobilePacksDirectory, { recursive: true });
for (const id of packIDs) {
  const pack = createNativePack(id, nativeCollections[id], BUILTIN_ICON_ROLE_MAPS[id]);
  const destination = resolve(mobilePacksDirectory, `${id}.generated.ts`);
  const output = await formatGeneratedTypescript(destination, renderNativePack(pack));
  await assertOrWrite(destination, output);

  for (const role of nativeTabRoles) {
    await generateNativeTabAssets(id, role, pack.icons[role]);
  }
}
const nativeTabSourcesDestination = resolve(
  root,
  "apps/mobile/src/theme/native-tab-icon-sources.generated.ts",
);
await assertOrWrite(
  nativeTabSourcesDestination,
  await formatGeneratedTypescript(nativeTabSourcesDestination, renderNativeTabSources()),
);

function renderPack(pack) {
  const lines = [
    "// Generated by scripts/generate-theme-icon-packs.mjs. Do not edit by hand.",
    "import type { ThemeIconPack } from '../types.js';",
    "",
    "const pack = {",
    `\tid: ${typescriptString(pack.id)},`,
    "\ticons: {",
  ];
  for (const [role, icon] of Object.entries(pack.icons)) {
    lines.push(
      `\t\t${typescriptKey(role)}: {`,
      `\t\t\tbody: ${typescriptString(icon.body)},`,
      `\t\t\tviewBox: ${typescriptString(icon.viewBox)}`,
      "\t\t},",
    );
  }
  lines[lines.length - 1] = "\t\t}";
  lines.push("\t}", "} satisfies ThemeIconPack;", "", "export default pack;", "");
  return lines.join("\n");
}

function createNativePack(id, collection, names) {
  return {
    id,
    icons: Object.fromEntries(
      Object.entries(names).map(([role, sourceGlyphId]) => {
        const collectionName = id === "heroicons-solid" ? `${sourceGlyphId}-solid` : sourceGlyphId;
        const icon = getIconData(collection, collectionName);
        if (!icon) throw new Error(`${id} is missing the ${role} native theme icon`);
        const rendered = iconToSVG(icon, { height: "1em", width: "1em" });
        return [
          role,
          {
            body: rendered.body,
            sourceGlyphId,
            viewBox: rendered.attributes.viewBox,
          },
        ];
      }),
    ),
  };
}

function renderNativePack(pack) {
  const lines = [
    "// Generated by scripts/generate-theme-icon-packs.mjs. Do not edit by hand.",
    "import type { NativeThemeIconPack } from '../icon-data.js';",
    "",
    "const pack = {",
    `  id: ${typescriptString(pack.id)},`,
    "  icons: {",
  ];
  for (const [role, icon] of Object.entries(pack.icons)) {
    lines.push(
      `    ${typescriptKey(role)}: {`,
      `      body: ${typescriptString(icon.body)},`,
      `      sourceGlyphId: ${typescriptString(icon.sourceGlyphId)},`,
      `      viewBox: ${typescriptString(icon.viewBox)},`,
      "    },",
    );
  }
  lines.push("  },", "} satisfies NativeThemeIconPack;", "", "export default pack;", "");
  return lines.join("\n");
}

function renderNativeTabSources() {
  const lines = [
    "// Generated by scripts/generate-theme-icon-packs.mjs. Do not edit by hand.",
    "import type { ImageSourcePropType } from 'react-native';",
    "import type { NativeIconPackId } from './contract.js';",
    "import type { NativeTabIconRole } from './native-tab-icon-selection.js';",
    "",
    "export const NATIVE_TAB_ICON_SOURCES = {",
  ];
  for (const packId of packIDs) {
    lines.push(`  ${typescriptKey(packId)}: {`);
    for (const role of nativeTabRoles) {
      lines.push(
        `    ${typescriptKey(role)}: require('../../assets/theme-icons/${packId}/${role}.png'),`,
      );
    }
    lines.push("  },");
  }
  lines.push(
    "} satisfies Readonly<",
    "  Record<NativeIconPackId, Readonly<Record<NativeTabIconRole, ImageSourcePropType>>>",
    ">;",
    "",
  );
  return lines.join("\n");
}

async function generateNativeTabAssets(packId, role, icon) {
  const directory = resolve(mobileAssetsDirectory, packId);
  await mkdir(directory, { recursive: true });
  const xml = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${icon.viewBox}" color="#fff">${icon.body}</svg>`;
  for (const scale of [1, 2, 3]) {
    const suffix = scale === 1 ? "" : `@${scale}x`;
    const output = await sharp(Buffer.from(xml))
      .resize(24 * scale, 24 * scale)
      .png()
      .toBuffer();
    await assertOrWrite(resolve(directory, `${role}${suffix}.png`), output);
  }
}

async function assertOrWrite(destination, output) {
  if (check) {
    const current = await readFile(destination).catch(() => Buffer.alloc(0));
    const expected = Buffer.isBuffer(output) ? output : Buffer.from(output);
    if (!current.equals(expected)) {
      throw new Error(`${destination} is stale. Run bun scripts/generate-theme-icon-packs.mjs.`);
    }
    return;
  }
  await writeFile(destination, output);
}

async function formatGeneratedTypescript(destination, source) {
  const result = await format(destination, source, { printWidth: 100 });
  if (result.errors.length > 0) {
    throw new Error(`Could not format generated native icon data for ${destination}`);
  }
  return result.code;
}

function typescriptKey(value) {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(value) ? value : typescriptString(value);
}

function typescriptString(value) {
  return `'${value
    .replaceAll("\\", "\\\\")
    .replaceAll("'", "\\'")
    .replaceAll("\r", "\\r")
    .replaceAll("\n", "\\n")}'`;
}
