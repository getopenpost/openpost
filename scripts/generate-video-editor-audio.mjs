import { createHash } from 'node:crypto';
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const repository = dirname(dirname(fileURLToPath(import.meta.url)));
const outputDirectory = join(repository, 'frontend/static/video-editor-audio/assets');
const generatedModule = join(
	repository,
	'frontend/src/lib/video-editor/bundled-audio.generated.ts'
);
const manifestPath = join(repository, 'frontend/static/video-editor-audio/manifest.json');
const sampleRate = 48_000;
const definitions = [
	['warm-pulse', 'Warm pulse', 'music', 8],
	['bright-step', 'Bright step', 'music', 8],
	['calm-grid', 'Calm grid', 'music', 8],
	['night-drive', 'Night drive', 'music', 8],
	['soft-launch', 'Soft launch', 'music', 8],
	['clean-motion', 'Clean motion', 'music', 8],
	['ambient-focus', 'Ambient focus', 'music', 8],
	['upbeat-loop', 'Upbeat loop', 'music', 8],
	['soft-click', 'Soft click', 'effect', 0.18],
	['deep-click', 'Deep click', 'effect', 0.24],
	['pop', 'Pop', 'effect', 0.32],
	['bright-pop', 'Bright pop', 'effect', 0.38],
	['short-whoosh', 'Short whoosh', 'effect', 0.65],
	['long-whoosh', 'Long whoosh', 'effect', 1.1],
	['success-chime', 'Success chime', 'effect', 0.9],
	['alert-chime', 'Alert chime', 'effect', 0.8],
	['transition-up', 'Transition up', 'effect', 0.7],
	['transition-down', 'Transition down', 'effect', 0.7],
	['tap', 'Tap', 'effect', 0.15],
	['confirm', 'Confirm', 'effect', 0.55]
];

await mkdir(outputDirectory, { recursive: true });
const assets = [];
for (let index = 0; index < definitions.length; index += 1) {
	const [id, name, kind, durationSeconds] = definitions[index];
	const frames = Math.ceil(durationSeconds * sampleRate);
	const left = new Float32Array(frames);
	const right = new Float32Array(frames);
	if (kind === 'music') synthesizeMusic(left, right, index);
	else synthesizeEffect(left, right, index - 8);
	master(left, right, kind === 'music' ? -18 : -16);
	const bytes = encodeWAV(left, right);
	const filename = `${id}.wav`;
	await writeFile(join(outputDirectory, filename), bytes);
	assets.push({
		id,
		name,
		kind,
		path: `/video-editor-audio/assets/${filename}`,
		mime_type: 'audio/wav',
		size_bytes: bytes.byteLength,
		sha256: createHash('sha256').update(bytes).digest('hex'),
		author: 'OpenPost contributors',
		license: 'CC0-1.0',
		license_url: 'https://creativecommons.org/publicdomain/zero/1.0/',
		duration_seconds: durationSeconds,
		sample_rate: sampleRate,
		channels: 2,
		integrated_loudness_target_lufs: kind === 'music' ? -18 : -16,
		peak_ceiling_dbfs: -1,
		loop_start_seconds: kind === 'music' ? 0 : null,
		loop_end_seconds: kind === 'music' ? durationSeconds : null
	});
}

const manifest = {
	version: 1,
	generated_by: 'scripts/generate-video-editor-audio.mjs',
	content_license: 'CC0-1.0',
	assets
};
await writeFile(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);
await writeFile(
	generatedModule,
	`// Generated by scripts/generate-video-editor-audio.mjs. Do not edit by hand.\n` +
		`export const BUNDLED_AUDIO_MANIFEST = ${JSON.stringify(manifest, null, 2)} as const;\n`
);

function synthesizeMusic(left, right, preset) {
	const roots = [110, 146.83, 130.81, 98, 164.81, 123.47, 174.61, 138.59];
	const bpms = [90, 112, 82, 104, 96, 118, 74, 124];
	const root = roots[preset] ?? 110;
	const beatSeconds = 60 / (bpms[preset] ?? 100);
	let noise = 0x12345678 ^ preset;
	for (let frame = 0; frame < left.length; frame += 1) {
		const time = frame / sampleRate;
		const beatTime = time % beatSeconds;
		const barPhase = (time / (beatSeconds * 4)) % 1;
		const chord = [1, 1.12246, 1.33484, 1.49831][Math.floor(barPhase * 4)] ?? 1;
		const pad =
			Math.sin(time * Math.PI * 2 * root * chord) * 0.1 +
			Math.sin(time * Math.PI * 2 * root * chord * 1.5) * 0.05 +
			Math.sin(time * Math.PI * 2 * root * chord * 2) * 0.025;
		const kick =
			Math.sin(time * Math.PI * 2 * (52 + 48 * Math.exp(-beatTime * 20))) *
			Math.exp(-beatTime * 14) *
			0.32;
		noise = (noise * 1664525 + 1013904223) >>> 0;
		const hatTime = time % (beatSeconds / 2);
		const hat = ((noise / 0xffffffff) * 2 - 1) * Math.exp(-hatTime * 55) * 0.045;
		const edge = Math.min(1, time / 0.04, (left.length / sampleRate - time) / 0.04);
		const sample = Math.tanh((pad + kick + hat) * Math.max(0, edge));
		left[frame] = sample * (0.94 + 0.06 * Math.sin(time * 0.7));
		right[frame] = sample * (0.94 + 0.06 * Math.cos(time * 0.73));
	}
}

function synthesizeEffect(left, right, preset) {
	let noise = 0x9e3779b9 ^ preset;
	for (let frame = 0; frame < left.length; frame += 1) {
		const time = frame / sampleRate;
		const progress = frame / Math.max(1, left.length - 1);
		const envelope = Math.sin(Math.PI * progress) * Math.exp(-progress * (preset < 4 ? 4 : 1));
		noise = (noise * 1103515245 + 12345) >>> 0;
		const white = (noise / 0xffffffff) * 2 - 1;
		let sample;
		if (preset === 4 || preset === 5) {
			sample =
				white * envelope * 0.28 +
				Math.sin(time * Math.PI * 2 * (180 + 900 * progress)) * envelope * 0.08;
		} else if (preset === 8 || preset === 9) {
			const sweep = preset === 8 ? 180 + progress * 900 : 980 - progress * 800;
			sample = Math.sin(time * Math.PI * 2 * sweep) * envelope * 0.3;
		} else {
			const base = [520, 180, 330, 720, 0, 0, 523, 392, 0, 0, 680, 587][preset] ?? 440;
			const second = preset === 6 || preset === 11 ? base * 1.5 : base * 1.25;
			sample =
				(Math.sin(time * Math.PI * 2 * base) * 0.28 +
					Math.sin(time * Math.PI * 2 * second) * 0.16 +
					white * 0.03) *
				envelope;
		}
		left[frame] = sample;
		right[frame] = sample * 0.97;
	}
}

function master(left, right, targetRMSDB) {
	let sum = 0;
	let peak = 0;
	for (let index = 0; index < left.length; index += 1) {
		const l = left[index] ?? 0;
		const r = right[index] ?? 0;
		sum += (l * l + r * r) / 2;
		peak = Math.max(peak, Math.abs(l), Math.abs(r));
	}
	const rms = Math.sqrt(sum / Math.max(1, left.length));
	const targetRMS = 10 ** (targetRMSDB / 20);
	const peakCeiling = 10 ** (-1 / 20);
	const gain = Math.min(targetRMS / Math.max(rms, 1e-9), peakCeiling / Math.max(peak, 1e-9));
	for (let index = 0; index < left.length; index += 1) {
		left[index] = Math.tanh((left[index] ?? 0) * gain);
		right[index] = Math.tanh((right[index] ?? 0) * gain);
	}
}

function encodeWAV(left, right) {
	const dataBytes = left.length * 4;
	const buffer = new ArrayBuffer(44 + dataBytes);
	const view = new DataView(buffer);
	writeASCII(view, 0, 'RIFF');
	view.setUint32(4, 36 + dataBytes, true);
	writeASCII(view, 8, 'WAVE');
	writeASCII(view, 12, 'fmt ');
	view.setUint32(16, 16, true);
	view.setUint16(20, 1, true);
	view.setUint16(22, 2, true);
	view.setUint32(24, sampleRate, true);
	view.setUint32(28, sampleRate * 4, true);
	view.setUint16(32, 4, true);
	view.setUint16(34, 16, true);
	writeASCII(view, 36, 'data');
	view.setUint32(40, dataBytes, true);
	let offset = 44;
	for (let frame = 0; frame < left.length; frame += 1) {
		view.setInt16(offset, Math.round(Math.max(-1, Math.min(1, left[frame] ?? 0)) * 32767), true);
		view.setInt16(
			offset + 2,
			Math.round(Math.max(-1, Math.min(1, right[frame] ?? 0)) * 32767),
			true
		);
		offset += 4;
	}
	return Buffer.from(buffer);
}

function writeASCII(view, offset, value) {
	for (let index = 0; index < value.length; index += 1) {
		view.setUint8(offset + index, value.charCodeAt(index));
	}
}
