import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const packsDirectory = resolve(root, "frontend/src/lib/themes/icons/packs");
const packIDs = ["lucide", "heroicons-outline", "heroicons-solid", "phosphor", "tabler"];
const check = process.argv.includes("--check");

for (const id of packIDs) {
  const source = await import(`${packsDirectory}/${id}.ts`);
  const output = renderPack(source.default);
  const destination = resolve(packsDirectory, `${id}.generated.ts`);
  if (check) {
    const current = await readFile(destination, "utf8").catch(() => "");
    if (current !== output) {
      throw new Error(`${destination} is stale. Run bun scripts/generate-theme-icon-packs.mjs.`);
    }
    continue;
  }
  await writeFile(destination, output);
}

function renderPack(pack) {
  const lines = [
    "// Generated by scripts/generate-theme-icon-packs.mjs. Do not edit by hand.",
    "import type { ThemeIconPack } from '../types.js';",
    "",
    "const pack = {",
    `\tid: ${typescriptString(pack.id)},`,
    "\ticons: {",
  ];
  for (const [role, icon] of Object.entries(pack.icons)) {
    lines.push(
      `\t\t${typescriptKey(role)}: {`,
      `\t\t\tbody: ${typescriptString(icon.body)},`,
      `\t\t\tviewBox: ${typescriptString(icon.viewBox)}`,
      "\t\t},",
    );
  }
  lines[lines.length - 1] = "\t\t}";
  lines.push("\t}", "} satisfies ThemeIconPack;", "", "export default pack;", "");
  return lines.join("\n");
}

function typescriptKey(value) {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(value) ? value : typescriptString(value);
}

function typescriptString(value) {
  return `'${value
    .replaceAll("\\", "\\\\")
    .replaceAll("'", "\\'")
    .replaceAll("\r", "\\r")
    .replaceAll("\n", "\\n")}'`;
}
